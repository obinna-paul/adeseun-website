import type { Metadata } from "next";

export const SITE_NAME = "Adeseun Oyeneye";
/**
 * Launching on Vercel's free subdomain rather than a custom domain for
 * now (direct instruction) — Vercel defaults an unclaimed project to
 * `<repo-name>.vercel.app`, so this predicts that value ahead of the
 * actual deploy. It's a prediction, not a confirmed value: if the
 * project gets a different name in the Vercel dashboard (or the name is
 * already taken and Vercel appends a suffix), update this to match the
 * real assigned URL once deployed — canonical links, the sitemap, and
 * every OG/Twitter absolute URL all derive from it.
 */
export const SITE_URL = "https://adeseun-website.vercel.app";
export const PERSON_ID = `${SITE_URL}/#adeseun`;
export const WEBSITE_ID = `${SITE_URL}/#website`;
/**
 * Executive-first, per direct instruction (superseding the earlier
 * author-first framing): the site's positioning now leads with her as a
 * Managing Director and entrepreneur, with authorship as one part of a
 * larger body of work rather than the headline. The role line itself is
 * reproduced from her own supplied website scope document, not invented
 * here — see the ADESEUN OYENEYE WEBSITE SCOPE BLUEPRINT's recommended
 * hero structure.
 */
const DEFAULT_DESCRIPTION =
  "Entrepreneur, media executive, architect, interior designer, and author — building businesses, shaping spaces, and telling African stories.";

type PageMetadataInput = {
  title: string;
  description?: string;
  path?: string; // e.g. "/books"
  noIndex?: boolean;
};

/**
 * Builds a Next.js Metadata object with consistent OG/Twitter defaults so
 * every page doesn't hand-roll its own social card config.
 * Usage: `export const metadata = pageMetadata({ title: "The Library", path: "/books" })`
 *
 * The OG/Twitter *image* is intentionally not set here — it's supplied by
 * the file-convention generators `app/opengraph-image.tsx` /
 * `app/twitter-image.tsx`, which Next merges into every route's metadata
 * automatically. That's one dynamically-rendered, always-present card
 * instead of a hard-coded path to a PNG that has to be kept in sync (the
 * old `/og-default.png` this replaced never existed on disk, so every
 * share fell back to no image).
 */
export function pageMetadata({
  title,
  description = DEFAULT_DESCRIPTION,
  path = "/",
  noIndex = false,
}: PageMetadataInput): Metadata {
  const url = new URL(path, SITE_URL).toString();
  const fullTitle = path === "/" ? SITE_NAME : `${title} — ${SITE_NAME}`;

  return {
    title: { absolute: fullTitle },
    description,
    alternates: { canonical: url },
    robots: noIndex
      ? { index: false, follow: false }
      : {
          index: true,
          follow: true,
          googleBot: {
            index: true,
            follow: true,
            "max-image-preview": "large",
            "max-snippet": -1,
            "max-video-preview": -1,
          },
        },
    openGraph: {
      title: fullTitle,
      description,
      url,
      siteName: SITE_NAME,
      locale: "en_NG",
      type: "website",
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
    },
  };
}

